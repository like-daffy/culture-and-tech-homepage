const codes = new Set(COUNTRY_CODES);

export function isCountryCode(value: unknown): value is string {
  return typeof value === "string" && codes.has(value);
}

/** Every country, named in the page's language and sorted by name. */
export function countryOptions(lang: PageLang): Array<{ code: string; name: string }> {
  const locale = lang === "ko" ? "ko-KR" : "en-US";
  let names: Intl.DisplayNames | null = null;
  try {
    names = new Intl.DisplayNames([locale], { type: "region" });
  } catch {
    names = null;
  }
  return COUNTRY_CODES.map((code) => ({ code, name: names?.of(code) ?? code })).sort((a, b) => a.name.localeCompare(b.name, locale));
}
